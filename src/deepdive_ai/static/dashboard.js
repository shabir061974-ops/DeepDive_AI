"use strict";
const $ = id => document.getElementById(id);
const agents = ["Planner", "Researcher", "Drafter", "Verifier", "Synthesizer"];
const icons = ["◈", "⌕", "≡", "◇", "▤"];
const state = {scenarios: [], events: [], result: null, busy: false, selected: "report", filter: "all"};

function node(tag, text, className) {
  const element = document.createElement(tag);
  if (text !== undefined && text !== null) element.textContent = text;
  if (className) element.className = className;
  return element;
}
function empty(target, title, description) {
  const box = node("div", null, "empty-state");
  box.append(node("div", "◇", "empty-symbol"), node("h3", title), node("p", description));
  target.replaceChildren(box);
}
function badge(status) { return node("span", status.replaceAll("_", " "), `badge ${status}`); }
function activeScenario() { return state.scenarios.find(item => item.id === $("scenario").value); }
function error(message) { $("error").textContent = message; $("error").hidden = !message; }
function view(name, focus = false) {
  if (!["report", "claims", "sources", "audit"].includes(name)) return;
  state.selected = name;
  document.querySelectorAll(".tabs button").forEach(tab => {
    const selected = tab.dataset.view === name;
    tab.setAttribute("aria-selected", String(selected)); tab.tabIndex = selected ? 0 : -1;
  });
  document.querySelectorAll(".nav-link").forEach(link => link.classList.toggle("selected", link.dataset.view === name));
  ["report", "claims", "sources", "audit"].forEach(panel => { $(`panel-${panel}`).hidden = panel !== name; });
  if (focus) $(`tab-${name}`).focus();
}
function showEvidence(id) {
  view("sources");
  const element = document.getElementById(`evidence-${id}`);
  if (element) { element.scrollIntoView({block: "center", behavior: "smooth"}); element.focus({preventScroll: true}); }
}
function sourceButton(id, label, className = "citation") {
  const button = node("button", label, className);
  button.type = "button"; button.addEventListener("click", () => showEvidence(id));
  return button;
}
function drawAgents() {
  const container = $("agents"); container.replaceChildren(); let complete = 0;
  agents.forEach((name, index) => {
    const records = state.events.filter(event => event.agent === name.toLowerCase());
    const latest = records.at(-1); const count = records.filter(event => event.type === "agent_completed").length;
    const status = latest?.type === "agent_started" ? "active" : latest?.type === "agent_failed" ? "failed" : count ? "complete" : "";
    if (status === "complete") complete++;
    const card = node("div", null, `agent-card ${status}`); const top = node("div", null, "agent-top");
    top.append(node("span", status === "complete" ? "✓" : icons[index], "agent-icon"), node("span", `0${index + 1}`, "agent-index"));
    const label = status === "active" ? "Executing" : status === "failed" ? "Stopped safely" : count ? `${count} execution${count > 1 ? "s" : ""} completed` : state.busy ? "Waiting" : "Not run";
    card.append(top, node("div", name, "agent-name"), node("div", label, "agent-state")); container.append(card);
  });
  $("workflow-progress").value = complete;
  $("progress-label").textContent = state.events.length ? `${complete}/5 agent types completed · ${state.events.filter(e => e.type === "agent_completed").length} actual step completions` : "Agent states update from actual execution events.";
}
function drawOverview() {
  const container = $("overview"); container.replaceChildren();
  const metrics = state.result?.metrics;
  const rows = [["Accepted claims", "supported"], ["Unsupported claims", "unsupported"], ["Insufficient evidence", "insufficient_evidence"], ["Fixture sources", "sources"], ["Evidence records", "evidence"], ["Research-again loops", "research_retries"], ["Scripted model calls", "scripted_model_calls"]];
  rows.forEach(([label, key], index) => {
    if (index === 3) container.append(node("div", null, "metric-divider"));
    const row = node("div", null, `metric-row ${key}`);
    row.append(node("span", label), node("strong", metrics ? String(metrics[key]) : "—")); container.append(row);
  });
}
function drawReport() {
  const target = $("report-content"), result = state.result;
  if (!result) return empty(target, "Your research, with a trail.", "Run a fixture scenario to inspect the report, verify claims and trace each citation to authored evidence.");
  if (!result.report) return empty(target, "The workflow stopped safely", "No final report was produced. Inspect the audit trail for the failed agent. No live request was made.");
  target.replaceChildren();
  const header = node("div", null, "report-header"); header.append(node("h3", "Fixture research report"), badge(result.report.status));
  target.append(header, node("p", "Authored offline evidence. Scripted model assessments. Accepted text and citations are generated by the real verification and synthesis logic.", "report-disclaimer"));
  target.append(node("h4", "Accepted claims", "subheading"));
  if (!result.summary.accepted_claims.length) {
    target.append(node("div", "No claim cleared verification. The system has not invented an answer.", "accepted-claim"));
  } else result.summary.accepted_claims.forEach(claim => {
    const block = node("div", claim.text, "accepted-claim");
    claim.citations.forEach((citation, i) => block.append(sourceButton(citation.evidence_id, `[${i + 1}]`)));
    target.append(block);
  });
  target.append(node("h4", "Research question", "subheading"), node("p", result.report.question.text, "reasoning"));
  target.append(node("p", "The verification ledger preserves every latest-draft claim, including rejected and unresolved assertions. Citation buttons open local fixture details; they do not navigate to the web.", "report-summary-note"));
}
function assessmentView(result, target) {
  let rationale;
  try { rationale = JSON.parse(result.rationale); } catch { target.append(node("p", result.rationale, "reasoning")); return; }
  const labels = node("div", null, "reasoning");
  labels.append(node("span", "Scripted verdict: "), badge(rationale.model_verdict), node("span", " → Backend classification: "), badge(rationale.effective_verdict)); target.append(labels);
  target.append(node("p", rationale.model_rationale, "reasoning"));
  rationale.assessments.forEach(item => {
    const block = node("div", null, `assessment ${item.relation}`);
    block.append(node("strong", item.relation.replaceAll("_", " ")));
    if (item.quote) block.append(node("blockquote", item.quote));
    block.append(node("p", item.rationale), sourceButton(item.evidence_id, "Inspect fixture evidence ↗", "small-button")); target.append(block);
  });
}
function drawClaims() {
  const target = $("claims-content"), report = state.result?.report;
  if (!report) return empty(target, "Verification is inspectable", "Supported, unsupported and insufficient-evidence classifications appear after a completed scenario.");
  target.replaceChildren();
  const filters = node("div", null, "filter-controls"), label = node("label", "Filter claims"); label.htmlFor = "claim-filter";
  const select = node("select"); select.id = "claim-filter";
  [["all", "All classifications"], ["supported", "Supported"], ["unsupported", "Unsupported"], ["insufficient_evidence", "Insufficient evidence"], ["contradictions", "With contradictory evidence"]].forEach(([value, title]) => { const option = node("option", title); option.value = value; select.append(option); });
  select.value = state.filter; select.addEventListener("change", () => { state.filter = select.value; drawClaims(); }); filters.append(label, select); target.append(filters);
  const selected = report.verification.filter(item => state.filter === "all" || item.status === state.filter ||
    (state.filter === "contradictions" && JSON.parse(item.rationale).assessments.some(row => row.relation === "contradicts")));
  if (!selected.length) target.append(node("p", "No claims in this classification. Empty evidence cannot produce a verified claim.", "reasoning"));
  selected.forEach(result => {
    const claim = report.claims.find(item => item.id === result.claim_id), card = node("article", null, "claim-card");
    card.append(badge(result.status), node("h3", claim.text), node("span", "Verification reasoning · scripted assessment", "field-label")); assessmentView(result, card); target.append(card);
  });
  const rounds = state.events.filter(event => event.type === "agent_completed" && event.agent === "verifier");
  if (rounds.length > 1) {
    target.append(node("h4", "Prior verification rounds", "subheading"));
    rounds.slice(0, -1).forEach((event, index) => {
      const block = node("article", null, "verification-round"); block.append(node("h4", `Round ${index + 1} · before research-again`));
      event.verification.forEach(result => assessmentView(result, block)); target.append(block);
    });
  }
}
function drawSources() {
  const target = $("sources-content"), report = state.result?.report;
  if (!report?.bundle.sources.length) return empty(target, "Evidence belongs here", "Fixture excerpts, source hashes, exact locators and provenance will appear here. No sources are invented for an empty result.");
  target.replaceChildren();
  report.bundle.sources.forEach((source, index) => {
    const card = node("article", null, "source-card"); card.append(node("h3", `${String(index + 1).padStart(2, "0")} / ${source.title}`), node("span", "Authored source · not a web citation", "tag amber"));
    report.bundle.evidence.filter(item => item.source_id === source.id).forEach(item => {
      const excerpt = node("blockquote", item.excerpt); excerpt.id = `evidence-${item.id}`; excerpt.tabIndex = -1;
      card.append(excerpt, node("p", item.locator), node("span", "Evidence identifier", "field-label"), node("code", item.id));
    });
    const details = node("details"); details.append(node("summary", "Inspect source provenance"), node("span", "Fixture identifier (offline)", "field-label"), node("code", source.url), node("span", "Original content SHA-256", "field-label"), node("code", source.provenance.content_sha256), node("span", "Retrieval method", "field-label"), node("p", source.provenance.retrieval_method), node("span", "Synthetic fixture timestamp · not a live retrieval", "field-label"), node("code", source.provenance.retrieved_at)); card.append(details); target.append(card);
  });
}
function drawAudit() {
  const target = $("audit-content");
  if (!state.events.length) return empty(target, "Nothing hidden behind the answer", "Actual agent calls and audit events are recorded in execution order. No activity or execution times are simulated.");
  target.replaceChildren();
  state.events.forEach(event => {
    const row = node("div", null, `audit-row ${event.kind || event.type}`), body = node("div");
    const title = event.type === "audit" ? `Workflow · ${event.kind.replaceAll("_", " ")}` : `${event.agent} · ${event.type.replace("agent_", "").replaceAll("_", " ")}`;
    body.append(node("div", title, "audit-title"), node("div", `#${event.sequence} · ${event.occurred_at}${event.attempt !== undefined ? ` · research attempt ${event.attempt}` : ""}`, "audit-meta"));
    if (event.tasks) event.tasks.forEach(task => body.append(node("p", task.instruction, "audit-detail")));
    if (event.kind === "retry") body.append(node("p", "Coordinator requested research again. The existing bounded retry policy applies.", "audit-detail"));
    if (event.verification) event.verification.forEach(item => body.append(badge(item.status)));
    row.append(node("span", event.kind === "retry" ? "↳" : "·", "audit-bullet"), body); target.append(row);
  });
}
function render() {
  drawAgents(); drawOverview(); drawReport(); drawClaims(); drawSources(); drawAudit();
  $("claims-count").textContent = state.result?.report ? state.result.report.claims.length : "—";
  $("sources-count").textContent = state.result?.report ? state.result.report.bundle.sources.length : "—";
  $("export").disabled = state.busy || !state.result?.markdown;
}
function resetScenario() {
  state.events = []; state.result = null; state.filter = "all"; error("");
  const selected = activeScenario(); $("question").textContent = selected?.question || "No fixture scenario available.";
  $("scenario-description").textContent = selected?.description || "The local backend did not return any scenarios.";
  $("run-status").textContent = "Ready to start"; render();
}
async function run() {
  if (state.busy || !activeScenario()) return;
  resetScenario(); state.busy = true; $("run").disabled = true; $("scenario").disabled = true;
  $("run").replaceChildren(node("span", "◌", "spin"), document.createTextNode(" Running demo"));
  $("run-status").textContent = "Executing actual offline workflow…"; view("audit"); render();
  let finished = false;
  try {
    const response = await fetch("/api/demo/runs", {method: "POST", headers: {"Content-Type": "application/json", "X-DeepDive-Demo": "offline"}, body: JSON.stringify({scenario_id: $("scenario").value})});
    if (!response.ok) throw new Error(response.status === 429 ? "The local demo is busy. Wait for a run to finish." : "The local backend rejected the demo request. No live research was started.");
    const reader = response.body.getReader(), decoder = new TextDecoder(); let pending = "", size = 0;
    while (true) {
      const {value, done} = await reader.read();
      if (done) break;
      size += value.length; if (size > 1000000) { await reader.cancel(); throw new Error("Demo response exceeded the display limit."); }
      pending += decoder.decode(value, {stream: true}); let split;
      while ((split = pending.indexOf("\n")) !== -1) {
        const line = pending.slice(0, split); pending = pending.slice(split + 1); if (!line) continue;
        const event = JSON.parse(line);
        if (event.type === "result") { state.result = event.data; state.events = event.data.events; finished = true; }
        else if (event.type === "error") throw new Error("The offline workflow failed safely. No live action was taken.");
        else state.events.push(event);
        render();
      }
    }
    if (!finished) throw new Error("The local execution stream ended before a result. Run state is incomplete.");
    if (state.result.status === "failed") { error(state.result.error); $("run-status").textContent = "Stopped safely · inspect audit trail"; view("audit"); }
    else { $("run-status").textContent = state.result.report.status === "verified" ? "Completed · fixture claims accepted" : "Completed · needs review"; view("report"); }
  } catch (problem) { error(problem.message === "Failed to fetch" ? "Local backend unavailable. Check that the local server is running." : problem.message); $("run-status").textContent = "Execution interrupted"; }
  finally { state.busy = false; $("run").disabled = !activeScenario(); $("scenario").disabled = false; $("run").replaceChildren(node("span", "▶"), document.createTextNode(" Run offline demo")); render(); }
}
$("run").addEventListener("click", run);
$("scenario").addEventListener("change", resetScenario);
document.querySelectorAll("[data-view]").forEach(button => button.addEventListener("click", () => view(button.dataset.view)));
document.querySelectorAll(".tabs button").forEach(button => button.addEventListener("keydown", event => {
  const names = ["report", "claims", "sources", "audit"];
  if (["ArrowLeft", "ArrowRight", "Home", "End"].includes(event.key)) {
    event.preventDefault(); const index = names.indexOf(state.selected);
    view(event.key === "Home" ? names[0] : event.key === "End" ? names[3] : names[(index + (event.key === "ArrowRight" ? 1 : 3)) % 4], true);
  }
}));
$("export").addEventListener("click", () => {
  if (!state.result?.markdown) return;
  const url = URL.createObjectURL(new Blob([state.result.markdown], {type: "text/markdown;charset=utf-8"}));
  const link = node("a"); link.href = url; link.download = `deepdive-offline-${state.result.scenario_id}.md`; document.body.append(link); link.click(); link.remove(); URL.revokeObjectURL(url);
});
async function initialize() {
  render();
  try {
    const response = await fetch("/api/demo/scenarios"); if (!response.ok) throw new Error("Local scenario service unavailable.");
    const data = await response.json(); if (!data.scenarios?.length) throw new Error("No offline fixture scenarios are available.");
    state.scenarios = data.scenarios; $("scenario").replaceChildren();
    state.scenarios.forEach(item => { const option = node("option", item.title); option.value = item.id; $("scenario").append(option); });
    $("scenario").disabled = false; $("run").disabled = false; resetScenario();
  } catch { $("question").textContent = "Local demo backend unavailable"; error("Unable to load offline scenarios. Start the FastAPI server locally and reload this page."); $("run-status").textContent = "Backend unavailable"; }
}
initialize();
